// Writes the airports migrations: 20261102131000_airports.sql (the table, its RLS and grants, and the first part of
// the seed) and 20261102131001_airports_seed_2.sql … (the rest), from OurAirports (https://ourairports.com/data/,
// public domain). Kept: every large_airport with an IATA code, plus medium airports with scheduled service (the golf
// trips: MRY Monterey, SAV Savannah, HHH Hilton Head, INV Inverness…), the medium ones in golf countries only.
//
// Why small and split: each migration is applied through the Supabase MCP as one text parameter, so the seed is
// compact (one `code|icao|name|city|country|lat|lon` line per airport, split in SQL) and cut into ~40 KB parts.
// lat/lon are rounded to 4 decimals (~11 m), plenty for a 15 nm traffic circle and "nearest airport".
//
// Usage: node scripts/gen-airports.mjs [path/to/airports.csv]   (no path: downloads the current CSV)
import fs from "node:fs";
import path from "node:path";

const SRC = "https://davidmegginson.github.io/ourairports-data/airports.csv";
const DIR = path.join(import.meta.dirname, "..", "supabase", "migrations");
const PART_BYTES = 40_000;
// Medium airports (scheduled service) are kept in the countries the course library and most golf trips are in.
const GOLF_COUNTRIES = new Set(["US", "CA", "GB", "IE", "MX", "AU", "JP", "ZA", "ES", "PT", "AE"]);

const csv = process.argv[2] ? fs.readFileSync(process.argv[2], "utf8") : await download(SRC);
const [header, ...records] = parseCsv(csv);
const col = Object.fromEntries(header.map((h, i) => [h, i]));
const get = (r, k) => (r[col[k]] ?? "").trim();

/** One CSV parse with quoted fields ("a, b" and "" escapes). */
function parseCsv(text) {
  const rows = [];
  let row = [], field = "", quoted = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quoted) {
      if (c === '"' && text[i + 1] === '"') { field += '"'; i++; }
      else if (c === '"') quoted = false;
      else field += c;
    } else if (c === '"') quoted = true;
    else if (c === ",") { row.push(field); field = ""; }
    else if (c === "\n" || c === "\r") {
      if (c === "\r" && text[i + 1] === "\n") i++;
      row.push(field); rows.push(row); row = []; field = "";
    } else field += c;
  }
  if (field || row.length) { row.push(field); rows.push(row); }
  return rows.filter((r) => r.length > 1);
}

async function download(url) {
  const res = await fetch(url, { headers: { "user-agent": "18Eagles/1.0 (class project; gen-airports)" } });
  if (!res.ok) throw new Error(`${url} answered HTTP ${res.status}`);
  return res.text();
}

// Fields go between `|`s on one line, so neither may appear inside one.
const clean = (s) => s.replace(/[|\r\n]+/g, " ").replace(/\s+/g, " ").trim();

const byCode = new Map();
for (const r of records) {
  const type = get(r, "type");
  const iata = get(r, "iata_code").toUpperCase();
  if (!/^[A-Z0-9]{3}$/.test(iata)) continue;
  const country = get(r, "iso_country");
  const large = type === "large_airport";
  const medium = type === "medium_airport" && get(r, "scheduled_service") === "yes" && GOLF_COUNTRIES.has(country);
  if (!large && !medium) continue;
  const lat = Number(get(r, "latitude_deg")), lon = Number(get(r, "longitude_deg"));
  if (!Number.isFinite(lat) || !Number.isFinite(lon)) continue;
  const a = {
    code: iata,
    icao: clean(get(r, "icao_code") || get(r, "gps_code")),
    name: clean(get(r, "name")),
    city: clean(get(r, "municipality")),
    country: clean(country),
    lat: Math.round(lat * 1e4) / 1e4,
    lon: Math.round(lon * 1e4) / 1e4,
    large,
  };
  // A code listed twice (rare): the large airport wins.
  const had = byCode.get(iata);
  if (!had || (a.large && !had.large)) byCode.set(iata, a);
}
const airports = [...byCode.values()].sort((x, y) => x.code.localeCompare(y.code));
const lines = airports.map((a) => [a.code, a.icao, a.name, a.city, a.country, a.lat, a.lon].join("|"));

// Cut the lines into parts of about PART_BYTES each.
const parts = [[]];
let size = 0;
for (const l of lines) {
  if (size + l.length > PART_BYTES && parts.at(-1).length) { parts.push([]); size = 0; }
  parts.at(-1).push(l);
  size += l.length + 1;
}
if (parts.length > 9) throw new Error(`${parts.length} parts: raise PART_BYTES (file names allow 9)`);

const insert = (part) => `insert into public.airports (code, icao, name, city, country, lat, lon)
select f[1], nullif(f[2], ''), f[3], nullif(f[4], ''), nullif(f[5], ''), f[6]::double precision, f[7]::double precision
from (select string_to_array(line, '|') as f from regexp_split_to_table($seed$
${part.join("\n")}
$seed$, '\\n') as line where line <> '') as s;
`;

const head = `-- GENERATED by scripts/gen-airports.mjs from OurAirports (https://ourairports.com/data/, public domain).
-- Don't edit by hand: re-run the script. ${airports.length} airports in ${parts.length} parts (this file and
-- 20261102131001_airports_seed_2.sql …): every large airport with an IATA code, and medium airports with scheduled
-- service in ${[...GOLF_COUNTRIES].join("/")}.
--
-- airports: the IATA codes the Flights page can follow, with where each one is (the worker asks adsb.lol for traffic
-- around lat/lon; the page finds the nearest one to each course). Reference data, the same for everyone: RLS on,
-- one select policy for signed-in golfers, no write grants (these seeds are the only writes). anon gets nothing.
create table public.airports (
  code    text primary key check (code ~ '^[A-Z0-9]{3}$'),
  icao    text,
  name    text not null,
  city    text,
  country text,
  lat     double precision not null check (lat between -90 and 90),
  lon     double precision not null check (lon between -180 and 180)
);

alter table public.airports enable row level security;
create policy "Signed-in golfers read airports" on public.airports for select to authenticated using (true);

grant select on public.airports to authenticated;
revoke all on public.airports from anon;
-- The project doesn't auto-expose new tables: the flights worker (service_role) reads lat/lon explicitly.
grant select on public.airports to service_role;

-- Seed, part 1 of ${parts.length}. One line per airport: code|icao|name|city|country|lat|lon.
`;

for (const f of fs.readdirSync(DIR)) if (/^20261102131(0\d\d)_airports.*\.sql$/.test(f)) fs.rmSync(path.join(DIR, f));
const written = [];
parts.forEach((part, i) => {
  const file = i === 0 ? "20261102131000_airports.sql" : `2026110213100${i}_airports_seed_${i + 1}.sql`;
  const body = i === 0 ? head + insert(part)
    : `-- GENERATED by scripts/gen-airports.mjs (see 20261102131000_airports.sql). OurAirports, public domain.\n-- Seed, part ${i + 1} of ${parts.length}. One line per airport: code|icao|name|city|country|lat|lon.\n` + insert(part);
  fs.writeFileSync(path.join(DIR, file), body);
  written.push(`${file} (${part.length} rows, ${(Buffer.byteLength(body) / 1024).toFixed(0)} KB)`);
});
console.log(`${airports.length} airports (${airports.filter((a) => a.large).length} large):\n  ${written.join("\n  ")}`);
// A fingerprint to compare with the database after applying (see the DESIGN_LOG entry for the query).
const fp = airports.map((a) => `${a.code}:${a.lat}:${a.lon}`).join(",");
const { createHash } = await import("node:crypto");
console.log(`fingerprint md5(code:lat:lon, ordered by code) = ${createHash("md5").update(fp).digest("hex")}`);
